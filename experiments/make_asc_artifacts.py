def nbi_count(N, M):
    H1 = 1
    while comb(H1+M, M-1) <= N: H1 += 1
    cnt = comb(H1+M-1, M-1)
    if H1 < M:
        H2 = 0
        while comb(H1+M-1, M-1)+comb(H2+M, M-1) <= N: H2 += 1
        if H2 > 0: cnt += comb(H2+M-1, M-1)
    return cnt

