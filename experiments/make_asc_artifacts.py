def vec(A, pp):
    if A is None: return np.array([])
    v = A.igd[pp]
    return np.atleast_1d(np.asarray(v, dtype=float))

def pair_p(a, b):
    n = min(len(a), len(b)); a, b = a[:n], b[:n]
    m = np.isfinite(a) & np.isfinite(b)
    if m.sum() < 5: return np.nan, 0, int(m.sum()), np.nan
    a2, b2 = a[m], b[m]
    wins = int(np.sum(a2 < b2))
    try: p = wilcoxon(a2, b2).pvalue
    except Exception: p = np.nan
    return p, wins, int(m.sum()), float(np.mean(a2)-np.mean(b2))

def fmt_p(p):
    if not np.isfinite(p): return '--'
    if p < 1e-4: return '$<10^{-4}$'
    if p < 0.001: return '$%.1e$' % p
    return '%.4f' % p

